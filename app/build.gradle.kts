abstract class SyncLegalAssetsTask : DefaultTask() {
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.NAME_ONLY)
    abstract val sourceFiles: ConfigurableFileCollection

    @get:OutputDirectory
    abstract val outputDir: DirectoryProperty

    @TaskAction
    fun copyFiles() {
        val out = outputDir.get().asFile
        out.deleteRecursively()
        out.mkdirs()
        sourceFiles.files.forEach { file ->
            file.copyTo(File(out, file.name), overwrite = true)
        }
    }
}

androidComponents {
    onVariants { variant ->
        val taskName = "sync${variant.name.replaceFirstChar { it.uppercaseChar() }}LegalAssets"
        val taskProvider = tasks.register<SyncLegalAssetsTask>(taskName) {
            sourceFiles.from(
                rootProject.file("LICENSE"),
                rootProject.file("THIRD_PARTY_NOTICES.md")
            )
        }
        variant.sources.assets?.addGeneratedSourceDirectory(
            taskProvider,
            SyncLegalAssetsTask::outputDir
        )
    }
}

